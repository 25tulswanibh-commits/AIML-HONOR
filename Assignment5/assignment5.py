def my_decorator(func):
    def wrapper(a, b):
        result = func(a, b)
        print("##########################")
        print("# Adding")
        print("# input:", a, b)
        print("# output:", result)
        print("##########################")
    return wrapper


@my_decorator
def add(a, b):
    return a + b


